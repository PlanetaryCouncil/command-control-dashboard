#!/usr/bin/env bash
# Write the daily report into docs/report/ and push it, so GitHub Pages
# serves it from this repo's own main branch.
#
# The report describes this dashboard, so it lives in this dashboard's repo.
# Marsita, 2026-09-03: "report of the dashboard belongs to dashboard" -- said
# after I offered to put it on the main site or in a new repo, both of which
# were answers to a question nobody had asked.
#
# Commits only when the content actually changed. A daily job that commits
# unconditionally turns the history into a heartbeat and buries the days
# something happened among the days nothing did.
set -uo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
PY="$REPO/.venv/bin/python"
cd "$REPO" || exit 1

OUT="$REPO/docs/report"
"$PY" fleet/bin/report.py --publish "$OUT" >/dev/null || { echo "report failed"; exit 1; }

# Stage first. `git diff` does not see untracked files, so the very first run
# -- the one where every file is new -- reported "unchanged" and published
# nothing (2026-09-03, caught on that first run).
git add -A docs/report

if git diff --cached --quiet -- docs/report 2>/dev/null; then
  echo "report unchanged"
  exit 0
fi

# generated_at changes every run, so a report where nothing happened still
# differs by a line or two per format. Below that threshold it is a timestamp,
# not news.
CHANGED=$(git diff --cached --numstat -- docs/report | awk '{a+=$1+$2} END {print a+0}')
if [[ "$CHANGED" -le 8 ]]; then
  echo "report changed only by its timestamp ($CHANGED lines) — not committing"
  git reset -q -- docs/report
  git checkout -- docs/report 2>/dev/null || true
  exit 0
fi

git commit -q -m "report: $(date -u +%Y-%m-%d) fleet summary

Generated by fleet/bin/report.py. Counted from the files the fleet writes
while working, not written by hand." || { echo "nothing to commit"; exit 0; }
git push -q && echo "published $(git log --oneline -1)"
